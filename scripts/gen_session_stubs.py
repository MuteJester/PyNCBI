"""Generate typed Session methods from the actual public function signatures."""

from __future__ import annotations

import argparse
import ast
import importlib
import inspect
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from PyNCBI.session import Session, _verb_registry  # noqa: E402


def build_stub() -> str:
    imports: dict[str, str] = {}
    needed: set[str] = set()

    def signature(func, method=True):
        module = importlib.import_module(func.__module__)
        tree = ast.parse(inspect.getsource(module))
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                imports[node.name] = f"from {module.__name__} import {node.name}"
            elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
                for alias in node.names:
                    imports[alias.asname or alias.name] = (
                        f"from {node.module} import {alias.name}"
                        + (f" as {alias.asname}" if alias.asname else "")
                    )
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    imports[alias.asname or alias.name.split(".")[0]] = f"import {alias.name}" + (
                        f" as {alias.asname}" if alias.asname else ""
                    )
        sig = inspect.signature(func)
        parameters = []
        for param in sig.parameters.values():
            if param.name == "self":
                continue
            if param.default is not inspect.Parameter.empty:
                param = param.replace(default=Ellipsis)
            parameters.append(param)
            if isinstance(param.annotation, str):
                needed.update(
                    n.id
                    for n in ast.walk(ast.parse(param.annotation, mode="eval"))
                    if isinstance(n, ast.Name)
                )
        if method:
            parameters.insert(0, inspect.Parameter("self", inspect.Parameter.POSITIONAL_OR_KEYWORD))
        if isinstance(sig.return_annotation, str):
            needed.update(
                n.id
                for n in ast.walk(ast.parse(sig.return_annotation, mode="eval"))
                if isinstance(n, ast.Name)
            )
        return str(sig.replace(parameters=parameters)).replace("Ellipsis", "...")

    lines = ["class Session:", "    name: str", "    config: Config", "    client: NCBIClient"]
    needed.update({"Config", "NCBIClient"})
    for name, obj in Session.__dict__.items():
        if name.startswith("_") and name not in ("__init__", "__enter__", "__exit__"):
            continue
        if isinstance(obj, staticmethod):
            lines.append("    @staticmethod")
            lines.append(f"    def {name}{signature(obj.__func__, method=False)}: ...")
        elif isinstance(obj, property):
            lines.append("    @property")
            lines.append(f"    def {name}{signature(obj.fget)}: ...")
        elif inspect.isfunction(obj):
            lines.append(f"    def {name}{signature(obj)}: ...")
    for name, func in sorted(_verb_registry().items()):
        lines.append(f"    def {name}{signature(func)}: ...")
    # Session return annotations refer to this class, not an imported alias.
    imports.pop("Session", None)
    header = [
        '"""Generated by scripts/gen_session_stubs.py; edit the Python signatures."""',
        "from __future__ import annotations",
    ]
    header += sorted({imports[n] for n in needed if n in imports})
    return "\n".join(header) + "\n\n" + "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "src" / "PyNCBI" / "session.pyi"
    content = build_stub()
    content = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--select",
            "I,UP037",
            "--fix",
            "--stdin-filename",
            str(target),
            "-",
        ],
        input=content,
        text=True,
        capture_output=True,
        check=True,
    ).stdout
    content = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(target), "-"],
        input=content,
        text=True,
        capture_output=True,
        check=True,
    ).stdout
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            parser.exit(1, "Run python scripts/gen_session_stubs.py\n")
    else:
        target.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
